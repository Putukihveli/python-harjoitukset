
hytti = input("Anna hytin luokka: ")
if hytti == "A":
    print("Hyttisi on ikkunallinen autokannen ylöpuolella. " )

elif hytti == "B": 
    print("Hyttisi on ikkunaton autokannen yläpuolella.")

elif hytti == "C": 
    print ("Hyttisi on ikkunaton autokannen alapuolella.")

elif hytti == "LUX": 
    print("Parvekkeellinen hytti yläkannella.")
    
else: 
    print ("Virheellinen hyttiluokka")